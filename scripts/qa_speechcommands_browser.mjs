import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from '/home/truongvu/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=root+'artifacts/audio_studio_web_20261018/';
const fixture={"wav": "/home/truongvu/Documents/C\u0110/CA-TCC-main/datasets/raw/speech_commands_v0.02/backward/067f61e2_nohash_0.wav"};
const browser=await chromium.launch({headless:true,executablePath:'/home/truongvu/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1434,height:801}});
const errors=[];
page.on('pageerror',e=>errors.push(String(e)));
await page.goto('http://127.0.0.1:8010',{waitUntil:'networkidle'});
await page.waitForFunction(()=>document.querySelector('#availability').textContent.includes('RAVDESS: sẵn sàng'));
await page.screenshot({path:output+'speechcommands-desktop-empty.png',fullPage:true});
await page.locator('#task').selectOption('SpeechCommands');
await page.locator('#file').setInputFiles(fixture.wav);
await page.waitForFunction(()=>!document.querySelector('#run').disabled);
if(await page.locator('.step:visible').count()!==1)throw new Error('Expected one upload screen');
await page.locator('#confirm-upload').click();
if(!await page.locator('#run-screen').isVisible()||await page.locator('#upload-screen').isVisible())throw new Error('Confirm did not advance');
await page.screenshot({path:output+'speechcommands-desktop-run.png',fullPage:true});
await page.locator('#run').click();
await page.waitForFunction(()=>document.querySelector('#result-badge').textContent==='Hoàn tất'||!document.querySelector('#notice').hidden,null,{timeout:120000});
const notice=await page.locator('#notice').textContent();
const ready=await page.locator('#result-badge').textContent();
if(ready!=='Hoàn tất')throw new Error('Inference failed: '+notice);
if(!await page.locator('#result-screen').isVisible()||await page.locator('.step:visible').count()!==1)throw new Error('Result did not advance automatically');
const result=await page.evaluate(()=>state.result);
const reference=JSON.parse(fs.readFileSync(root+'artifacts/dinov3_app_bundles/api_verification.json','utf8')).datasets.SpeechCommands.response.top_k[0];
if(result.items[0].label!==reference.label||Math.abs(result.items[0].probability-reference.probability)>0.002)throw new Error('Browser inference does not match the verified CPU model');
await page.waitForFunction(()=>!document.querySelector('#run').disabled);
await page.screenshot({path:output+'speechcommands-desktop-result.png',fullPage:true,animations:'disabled'});
const downloadPromise=page.waitForEvent('download');
await page.locator('#download').click();
const download=await downloadPromise;
await download.saveAs(output+'speechcommands-download.csv');
await page.locator('#new-audio').click();
if(!await page.locator('#upload-screen').isVisible())throw new Error('New audio did not return to upload');
await page.locator('#task').selectOption('auto');
await page.waitForFunction(()=>document.querySelector('#model-name').textContent.includes('RAVDESS'));
const mobile=await browser.newPage({viewport:{width:390,height:844}});
await mobile.goto('http://127.0.0.1:8010',{waitUntil:'networkidle'});
await mobile.screenshot({path:output+'speechcommands-mobile.png',fullPage:true});
const overflow=await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw new Error('Mobile layout overflows horizontally');
for(const width of [320,768,1024]){await mobile.setViewportSize({width,height:844});if(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Layout overflows at '+width);if(await mobile.locator('.step:visible').count()!==1)throw new Error('Multiple screens visible');}
if(errors.length)throw new Error(errors.join('\n'));
fs.writeFileSync(output+'speechcommands-browser_verification.json',JSON.stringify({passed:true,result,csv_download:download.suggestedFilename(),mobile_horizontal_overflow:overflow,page_errors:errors},null,2));
await browser.close();
console.log('Desktop/mobile UI, real browser inference, model selection and CSV download passed.');
